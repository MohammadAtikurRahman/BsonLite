'use strict';
const {MongoClient}=require('mongodb');
const {parseQuery,validatePlan,json,fromJSON,HELP}=require('./query.cjs');
const {executePlan}=require('./execute.cjs');
function safeError(error){
  return String(error?.message||error).replace(/(?:mongodb(?:\+srv)?|bsonlite):\/\/[^\s"']+/gi,'[connection URL]').replace(/Bearer\s+[a-f0-9]{64}/gi,'[token]').slice(0,1500);
}
function bridgeURL(value){const u=new URL(value);if(u.protocol!=='bsonlite:'||u.hostname!=='127.0.0.1'||!u.port||u.username||u.password||u.search||!/^#[a-f0-9]{64}$/.test(u.hash))throw new Error('Use the exact local bsonlite:// URL generated by startBridge().');return u;}
class Connection {
  constructor(){this.adapter=null;this.database='';this.readOnly=true;this.busy=false;this.connecting=false;}
  async connect(options){
    if(this.connecting||this.busy)throw new Error('Wait for the current operation to finish.');
    this.connecting=true;let candidate;
    try {
      if(typeof options?.uri!=='string'||options.uri.length>16384)throw new Error('Enter a connection URL.');
      const uri=options.uri.trim();
      if(uri.startsWith('bsonlite://')){
        const u=bridgeURL(uri),base=`http://127.0.0.1:${u.port}`;
        const request=async(path,body)=>{
          const response=await fetch(base+path,{method:body===undefined?'GET':'POST',headers:{Authorization:'Bearer '+u.hash.slice(1),'Content-Type':'application/json'},body:body===undefined?undefined:json(body,0),signal:AbortSignal.timeout(20000),redirect:'error'});
          const txt=await response.text();if(txt.length>20*1024*1024)throw new Error('Result too large.');const data=fromJSON(txt);if(!response.ok)throw new Error(data.error||'Connection failed.');return data;
        };
        const info=await request('/info');
        if(info.protocol!==1||typeof info.name!=='string'||decodeURIComponent(u.pathname.slice(1))!==info.name)throw new Error('Invalid bridge response or database name.');
        candidate={kind:'BsonLite app',name:info.name,allowWrites:info.allowWrites===true,allowCommands:false,databases:async()=>[{name:info.name}],execute:plan=>request('/execute',plan),close:async()=>{}};
      }else{
        if(!/^mongodb(?:\+srv)?:\/\//.test(uri))throw new Error('Use a bsonlite://, mongodb:// or mongodb+srv:// connection URL.');
        // TLS checks always remain enabled. Never accept insecure URI overrides.
        const query=uri.split('?')[1]||'';
        for(const [key,value]of new URLSearchParams(query))if(/^(tlsInsecure|tlsAllowInvalidCertificates|tlsAllowInvalidHostnames)$/i.test(key)&&value.toLowerCase()!=='false')throw new Error('Invalid TLS certificates and hostnames cannot be bypassed.');
        const opts={appName:'BsonLite Console',serverSelectionTimeoutMS:8000,connectTimeoutMS:8000,socketTimeoutMS:15000,maxPoolSize:4,retryWrites:false};
        for(const key of ['tlsCAFile','tlsCertificateKeyFile'])if(options[key]){if(typeof options[key]!=='string')throw new Error('Invalid certificate path.');opts[key]=options[key];opts.tls=true;}
        const client=new MongoClient(uri,opts);
        try{
          await client.connect();let name=options.database?.trim()||client.db().databaseName;
          await client.db(name).command({ping:1});
          candidate={kind:'Direct URI',name,allowWrites:true,allowCommands:true,databases:async()=>{
            try{return(await client.db('admin').admin().listDatabases({authorizedDatabases:true,nameOnly:true,maxTimeMS:10000})).databases;}
            catch(error){if(error.code===13||error.codeName==='Unauthorized')return[{name}];throw error;}
          },execute:plan=>executePlan(db=>client.db(db),plan,{readOnly:this.readOnly}),close:()=>client.close()};
        }catch(e){await client.close();throw e;}
      }
      await this.adapter?.close();this.adapter=candidate;this.database=candidate.name;this.readOnly=options.readOnly!==false;
      return {connected:true,database:this.database,kind:candidate.kind,readOnly:this.readOnly,allowWrites:candidate.allowWrites};
    }catch(error){await candidate?.close();throw new Error(safeError(error));}finally{this.connecting=false;}
  }
  async disconnect(){if(this.busy||this.connecting)throw new Error('Wait for the current operation to finish.');await this.adapter?.close();this.adapter=null;this.database='';}
  async run(source){
    return this.runPlan(parseQuery(source,this.database));
  }
  async runPlan(plan){
    if(!this.adapter)throw new Error('Connect to a database first.');if(this.busy)throw new Error('An operation is already running.');
    this.busy=true;const started=performance.now();
    try{
      validatePlan(plan,{readOnly:this.readOnly||!this.adapter.allowWrites,allowCommands:this.adapter.allowCommands});
      let result;
      if(plan.type==='help')result={value:HELP};
      else if(plan.type==='databases')result={value:await this.adapter.databases()};
      else if(plan.type==='use'){if(this.adapter.kind==='BsonLite app'&&plan.database!==this.adapter.name)throw new Error('This URL grants access only to database '+this.adapter.name+'.');this.database=plan.database;result={value:{database:this.database}};}
      else result=await this.adapter.execute(plan);
      const text=json(result.value);if(Buffer.byteLength(text)>20*1024*1024)throw new Error('Result exceeds 20 MB. Use a smaller limit or a projection.');
      return {...result,text,milliseconds:Math.round(performance.now()-started),database:this.database,count:Array.isArray(result.value)?result.value.length:undefined};
    }catch(error){throw new Error(safeError(error));}finally{this.busy=false;}
  }
}
module.exports={Connection,bridgeURL,safeError};
